def render():
    st.markdown(
        "Export your completed diagram as TTool-compatible XML "
        "and save it to the knowledge base for future CBR retrieval."
    )

    # -- Summary --------------------------------------------------------------
    with st.expander("Current Diagram Summary", expanded=True):
        col1, col2 = st.columns(2)
        with col1:
            st.write("**System:**",
                     st.session_state.get("ucd_system_name") or "-")
            st.write("**Primary Actors:**",
                     ", ".join(st.session_state.get("ucd_primary_actors") or []) or "-")
            st.write("**Secondary Actors:**",
                     ", ".join(st.session_state.get("ucd_secondary_actors") or []) or "-")
        with col2:
            st.write("**Use Cases:**",
                     ", ".join(st.session_state.get("ucd_use_cases") or []) or "-")
            rels = st.session_state.get("ucd_relationships") or []
            st.write(f"**Relationships:** {len(rels)}")

        col1, col2 = st.columns(2)
        with col1:
            st.write("**System:**",
                     st.session_state.get("ucd_system_name") or "-")
            st.write("**Primary Actors:**",
                     ", ".join(st.session_state.get("ucd_primary_actors") or []) or "-")
            st.write("**Secondary Actors:**",
                     ", ".join(st.session_state.get("ucd_secondary_actors") or []) or "-")
        with col2:
            st.write("**Use Cases:**",
                     ", ".join(st.session_state.get("ucd_use_cases") or []) or "-")
            rels = st.session_state.get("ucd_relationships") or []
            st.write(f"**Relationships:** {len(rels)}")

    st.divider()

    # -- TTool XML Generation & Download --------------------------------------
    st.subheader("TTool XML Export")

    base_xml = st.session_state.get("ucd_ttool_xml_base")
    ttool_xml = st.session_state.get("ucd_ttool_xml")
    validation = st.session_state.get("ucd_generation_validation")

    try:
        current_signature = _current_export_signature()
        stored_signature  = st.session_state.get("ucd_generation_export_signature")
        if current_signature != stored_signature or not ttool_xml:
            with st.spinner("Generating TTool XML with Requirements and Verification tabs..."):
                base_xml, validation, ttool_xml = _build_generation_export_bundle()
            st.session_state["ucd_ttool_xml_base"] = base_xml
            st.session_state["ucd_ttool_xml"] = ttool_xml
            st.session_state["ucd_generation_validation"] = validation
            st.session_state["ucd_generation_export_signature"] = current_signature
    except Exception as _xe:
        st.warning(f"TTool XML generation skipped: {_xe}")
        base_xml = None
        ttool_xml = None

    if ttool_xml:
        from datetime import date
        from verification.ttool_launcher import (
            launch_ttool_with_file,
            save_xml_to_default_downloads,
        )

        sys_name  = st.session_state.get("ucd_system_name") or "Untitled"
        safe_name = _safe_name(sys_name)
        date_str  = date.today().strftime("%Y-%m-%d")
        export_name = f"{safe_name}_ttool_verified_{date_str}.xml"
        st.success(
            "TTool XML ready - generated automatically from your diagram "
            "with Verification and Requirements tabs."
        )
        st.info(
            "Use `Save Session` only to resume the wizard later. "
            "Use the download below for the real TTool XML file that contains "
            "the Verification and Requirements tabs."
        )
        download_clicked = st.download_button(
            "Download TTool UCD XML",
            data=ttool_xml,
            file_name=export_name,
            mime="application/xml",
            use_container_width=True,
            key="btn_ttool_dl",
        )
        if download_clicked:
            default_ttool = "C:\\Users\\mages\\Downloads\\releaseTTool_2_0\\TTool\\ttool_windows.bat"
            ttool_path = st.session_state.get("ttool_path", default_ttool)
            st.session_state["ttool_path"] = ttool_path
            try:
                saved_path = save_xml_to_default_downloads(export_name, ttool_xml)
            except Exception as e:
                st.warning(f"Download started, but the local XML copy could not be saved to Downloads: {e}")
            else:
                ok, msg = launch_ttool_with_file(ttool_path, saved_path)
                if ok:
                    st.info(f"TTool opened with {saved_path}")
                else:
                    st.warning(f"Download started and XML was saved to {saved_path}, but TTool was not opened: {msg}")
        with st.expander("Preview TTool XML", expanded=False):
            st.text_area("TTool XML", value=ttool_xml, height=220,
                         label_visibility="collapsed", key="ttool_preview")
    else:
        st.warning("TTool XML could not be generated.")

    # -- Automatic Validation --------------------------------------------------
    st.divider()
    st.subheader("Automatic Validation Review")
    st.caption(
        "After generation, the diagram is validated automatically for naming, "
        "uniqueness, arrangement, and connectivity. Relationship-type checking "
        "(association/include/extend/generalization) is intentionally skipped here."
    )

    if validation:
        col1, col2, col3 = st.columns(3)
        col1.metric("Total Issues", validation.get("total", 0))
        col2.metric("Errors", validation.get("errors", 0))
        col3.metric("Warnings", validation.get("warnings", 0))

        if validation.get("total", 0) == 0:
            st.success("No non-relationship validation issues were detected in the generated diagram.")
        else:
            st.warning(
                f"Detected **{validation.get('total', 0)}** non-relationship issue(s). "
                "Review them before using the generated diagram downstream."
            )

        with st.expander("Validation Findings", expanded=validation.get("total", 0) > 0):
            issues = validation.get("issues") or []
            for i, issue in enumerate(issues, 1):
                if issue.startswith("[ERR] "):
                    st.markdown(f"**{i}.** :red[{issue}]")
                elif issue.startswith("[WARN] "):
                    st.markdown(f"**{i}.** :orange[{issue}]")
                else:
                    st.markdown(f"**{i}.** {issue}")
    else:
        st.info("Validation results will appear here once the TTool XML is available.")

    st.divider()

    # -- Save to Case Base ----------------------------------------------------
    st.subheader("Save to Case Base")
    already_saved = st.session_state.get("_saved_case_id")
    if already_saved:
        st.info(f"Already saved as Case ID **{already_saved}** this session. "
                "Re-saving will create a duplicate - use only if you changed the diagram.")

    if st.button("Save Case to Database", key="btn_save_db",
                 use_container_width=True, type="primary"):
        try:
            with st.spinner("Saving to case base..."):
                _save_to_case_base()
        except Exception as e:
            st.error(f"Save failed: {e}")

    st.divider()

    # -- SysML v2 Diagram & Download ------------------------------------------
    st.subheader("SysML v2 Use Case Diagram")
    from generation.sysml_ucd import render_sysml_panel
    render_sysml_panel(key="step9")

    # Navigation
    render_navigation(show_next=False)
    st.success("You have completed all steps!")


